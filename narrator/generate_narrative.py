# TASK 5 NUMERIC CHECKER
# ============================================================

def check_narrative_numbers(narrative: str) -> bool:
    """
    Check that the required figures from the project brief
    appear in the generated narrative.
    """

    normalized = narrative.replace(",", "")

    checks = {
        "97,358.30 cleaned revenue": (
            "97358.30" in normalized or
            "97358.3" in normalized
        ),

        "44.4 COD return rate": (
            "44.4" in normalized
        ),

        "54.5 COD + Tier-2 risk rate": (
            "54.5" in normalized
        ),

        "2,501.90 reconciliation delta": (
            "2501.90" in normalized or
            "2501.9" in normalized
        ),

        "March + 20,318.90 peak revenue": (
            "March" in narrative and
            (
                "20318.90" in normalized or
                "20318.9" in normalized
            )
        )
    }

    all_passed = True

    print("\nNumeric Accuracy Checker")
    print("=" * 60)

    for label, passed in checks.items():

        if passed:
            print(f"PASS - {label}")
        else:
            print(f"FAIL - {label}")
            all_passed = False

    print("=" * 60)

    if all_passed:
        print("NUMERIC CHECK: PASS")
    else:
        print("NUMERIC CHECK: FAIL")

    return all_passed


# ============================================================
# MAIN RUNNER
# ============================================================

def main():


    findings_path = Path("/content/findings.json")

    # Save the generated narrative directly into /content.
    sample_output_path = Path("/content/sample_output.txt")

    # Check that findings.json exists before trying to open it.
    if not findings_path.exists():
        raise FileNotFoundError(
            f"Could not find {findings_path}. "
            "Upload findings.json to the Colab notebook first."
        )

    print("Loading findings from:")
    print(findings_path)

    with open(findings_path, "r", encoding="utf-8") as file:
        findings = json.load(file)

    print("findings.json loaded successfully.")

    print("\nStarting narrative generation...")
    result = generate_scr_narrative(findings)

    print("\nNarrative generation result")
    print("=" * 60)
    print("Status:", result["status"])
    print("Tokens:", result.get("tokens"))

    print("\nGenerated narrative:")
    print("-" * 60)
    print(result["narrative"])

    # Save the actual generated narrative.
    with open(sample_output_path, "w", encoding="utf-8") as file:
        file.write(result["narrative"])

    print("\nSaved:")
    print(sample_output_path)

    # Check the generated narrative.
    generated_check = check_narrative_numbers(
        result["narrative"]
    )

    # Check the saved sample exactly as it was written.
    with open(sample_output_path, "r", encoding="utf-8") as file:
        saved_narrative = file.read()

    print("\nChecker against /content/sample_output.txt")

    saved_check = check_narrative_numbers(
        saved_narrative
    )

    print("\nFinal Task 5 Result")
    print("=" * 60)

    if generated_check and saved_check:
        print("PASS - All required numeric figures are present.")
    else:
        print("FAIL - One or more required numeric figures are missing.")


if __name__ == "__main__":
    main()