import json
import os
from pathlib import Path

from google import genai
from google.genai import types


# ============================================================
# OFFLINE FALLBACK
# ============================================================

def generate_scr_narrative_offline(findings: dict) -> dict:
    """
    Deterministic fallback that generates the SCR narrative
    directly from findings.json without using Gemini.
    """

    cleaned_revenue = findings["cleaned_total_revenue_inr"]
    duplicate_delta = findings["duplicate_reconciliation_delta_inr"]

    cod_rate = findings["return_rate_by_payment"]["COD"]

    risk_payment = findings["highest_risk_segment"]["payment_method"]
    risk_tier = findings["highest_risk_segment"]["city_tier"]
    risk_rate = findings["highest_risk_segment"]["return_rate_pct"]

    peak_month = findings["true_peak_month"]["month"]
    peak_revenue = findings["true_peak_month"]["revenue_inr"]

    month_names = {
        "01": "January",
        "02": "February",
        "03": "March",
        "04": "April",
        "05": "May",
        "06": "June",
        "07": "July",
        "08": "August",
        "09": "September",
        "10": "October",
        "11": "November",
        "12": "December"
    }

    peak_month_name = month_names[peak_month[-2:]]

    narrative = f"""Situation

The business recorded cleaned total revenue of {cleaned_revenue:,.2f} INR after a duplicate-driven reconciliation delta of {duplicate_delta:,.2f} INR. The validated peak month was {peak_month_name}, with revenue of {peak_revenue:,.2f} INR.

Complication

COD has a return rate of {cod_rate:.1f}%. The highest-risk segment is {risk_payment} in Tier-{risk_tier}, where the return rate is {risk_rate:.1f}%.

Resolution

Regional operations and finance teams should use the cleaned revenue as the reporting baseline, monitor COD returns closely, and focus operational review on the identified Tier-{risk_tier} segment while using {peak_month_name} as the validated peak-month reference.
"""

    return {
        "status": "success",
        "narrative": narrative,
        "tokens": None
    }


# ============================================================
# GEMINI NARRATIVE GENERATOR
# ============================================================

def generate_scr_narrative(findings: dict) -> dict:
    """
    Generate the SCR narrative using Gemini when an API key exists.
    Falls back to the deterministic offline function on failure.
    """

    # Your Gemini API key environment variable is named SG_api_key.
    api_key = os.getenv("SG_api_key")

    # No API key: immediately use the deterministic offline path.
    if not api_key:
        print("SG_api_key not found.")
        print("Using deterministic offline fallback.")
        return generate_scr_narrative_offline(findings)

    try:
        client = genai.Client(api_key=api_key)

        # Temperature 0.0 is intentional because this is a factual
        # business report, not creative writing, so deterministic output
        # is preferred.
        system_instruction = """
You are a senior data analyst writing for Mamaearth's regional ops
and finance heads.

Write the narrative using exactly three labeled sections, in this order:

Situation
Complication
Resolution

Use ONLY the supplied findings.

Every number in the output must come from the supplied findings
and must appear with the same value. Do not invent, estimate,
calculate, round, or introduce any new statistics.

Do not introduce additional percentages, revenue figures,
ratios, order counts, dates, or other numerical values.

Preserve the supplied numerical values accurately.

Keep the narrative concise, factual, and suitable for regional
operations and finance leadership.
"""

        # The numbers are taken from the findings argument.
        # Nothing is hardcoded here.
        contents = f"""
Create the required Situation-Complication-Resolution business
narrative from these verified findings:

{json.dumps(findings, indent=2)}

Every number used in the narrative must come from these findings.
"""

        response = client.models.generate_content(
            model="gemini-2.5-flash",
            contents=contents,
            config=types.GenerateContentConfig(
                system_instruction=system_instruction,
                temperature=0.0,
                max_output_tokens=500,
                http_options=types.HttpOptions(
                    timeout=30000
                )
            )
        )

        narrative = response.text

        # Try to obtain usage information when available.
        tokens = None

        if getattr(response, "usage_metadata", None):
            tokens = getattr(
                response.usage_metadata,
                "total_token_count",
                None
            )

        return {
            "status": "success",
            "narrative": narrative,
            "tokens": tokens
        }

    except Exception as err:
        print("Gemini API failed.")
        print(f"Reason: {err}")
        print("Using deterministic offline fallback.")

        return generate_scr_narrative_offline(findings)


